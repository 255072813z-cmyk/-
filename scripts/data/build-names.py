# 译音由一套拉丁转写自动转成俄文、塔吉克文、乌兹别克文写法；意思五种语言（塔、俄、乌、吉为初稿，待审定）。
import json, re, sys
D, OUT = sys.argv[1], sys.argv[2]
t = re.sub(r'[‏‎]', '', json.load(open(f'{D}/ara-tirmidhi-3507.json'))['hadiths'][0]['text'])
MARK = re.compile(r'[ً-ْٰـ]')
def find(src, bare_word, frm=0):
    keep = [i for i, c in enumerate(src) if not MARK.match(c)]
    bare = ''.join(src[i] for i in keep)
    j = bare.index(bare_word, frm)
    return keep[j], j + len(bare_word), keep
a0, _, keep = find(t, 'هو الله الذي')
r0, _, _ = find(t, 'الرحمن الرحيم')
_, e1, _ = find(t, 'الرشيد الصبور')
end = keep[e1 - 1] + 1
while end < len(t) and MARK.match(t[end]): end += 1
first_start = t.index(' ', a0) + 1
first = t[first_start:t.index(' ', first_start)]   # 原文里的"اللَّهُ"
rest = t[r0:end]
words = rest.split()
assert MARK.sub('', first) == 'الله', first
names = [first]
i = 0
while i < len(words):
    w = words[i]
    if MARK.sub('', w) == 'مالك':
        names.append(' '.join(words[i:i + 2])); i += 2; continue
    if MARK.sub('', w) == 'ذو':
        names.append(' '.join(words[i:i + 3])); i += 3; continue
    names.append(w); i += 1
assert len(names) == 99, len(names)
