# 拉丁转写 → 俄文 / 塔吉克文 / 乌兹别克文（按规则，双写辅音照写）
DI = [('kh','х','х','x'),('gh','г','ғ','gʻ'),('sh','ш','ш','sh'),('th','с','с','s'),('dh','з','з','z')]
SI = {'ā':('а','о','o'),'ī':('и','и','iy'),'ū':('у','у','u'),'a':('а','а','a'),'i':('и','и','i'),'u':('у','у','u'),'b':('б','б','b'),'t':('т','т','t'),
      'j':('дж','ҷ','j'),'ḥ':('х','ҳ','h'),'d':('д','д','d'),'r':('р','р','r'),'z':('з','з','z'),'s':('с','с','s'),'ṣ':('с','с','s'),'ḍ':('д','з','z'),
      'ṭ':('т','т','t'),'ẓ':('з','з','z'),'ʿ':('','ъ','ʼ'),'ʾ':('','ъ','ʼ'),'f':('ф','ф','f'),'q':('к','қ','q'),'k':('к','к','k'),'l':('л','л','l'),
      'm':('м','м','m'),'n':('н','н','n'),'h':('х','ҳ','h'),'w':('в','в','v'),'y':('й','й','y'),'-':('-','-','-'),' ':(' ',' ',' ')}
def conv(s, k):
    out=''; i=0; low=s.lower()
    while i < len(low):
        two = low[i:i+2]
        hit = next((d for d in DI if d[0]==two), None)
        if hit: out += hit[k+1]; i += 2; continue
        c = low[i]
        if c not in SI: raise SystemExit(f'未知字母 {c} in {s}')
        out += SI[c][k]; i += 1
    # 俄文冠词习惯写成"аль-"；首字母大写；每个词的首字母大写（冠词除外）
    if k == 0: out = re.sub(r'(^| )ал-', r'\1аль-', out)
    parts = out.split(' ')
    def cap(w):
        if '-' in w:
            a, b = w.split('-', 1)
            return a[:1].upper() + a[1:] + '-' + b[:1].upper() + b[1:]
        return w[:1].upper() + w[1:]
    return ' '.join(cap(w) if (j == 0 or not re.match(r'^(ва|вал|wal)', w)) else w for j, w in enumerate(parts))
