/** 某天的"今日圣训"（按当地日期轮换，同一天大家看到的一样） */
export function dailyHadith(ymd) {
  const n = Math.floor(Date.UTC(ymd.y, ymd.m - 1, ymd.d) / 864e5);
  const k = DAILY[((n % DAILY.length) + DAILY.length) % DAILY.length];
  return { key: k, ...HADITH[k] };
}
